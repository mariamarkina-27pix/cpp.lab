#include <iostream>  // Подключает биб-у ввода-вывода
#include <vector>    // Подключает биб-у для работы с динам массивами векторами
#include <clocale>   // Подключает биб-у для настройки локали кирилицы

using namespace std;

bool isSafe(int v, const vector<vector<int>>& graph, const vector<int>& color, int c) {// Фун-я для проверки, можно ли покрасить вершину v в цвет c безопасно
    for (int i = 0; i < graph.size(); ++i) { // Проходим циклом по всем вершинам графа

        if (graph[v][i] && color[i] == c) { // graph[v][i] = 1 означает, что вершины соединены, а color[i] = c — что сосед уже покрашен в этот цвет
            return false; // Если нашли конфликт, красить сюда нельзя
        }
    }
    return true; // Если конфликтов нет, цвет подходит
}


bool graphColoringUtil(const vector<vector<int>>& graph, int k, vector<int>& color, int v) {// Рекурсивная функция поиска раскраски (метод перебора с возвратом

    if (v == graph.size()) { // если дошли до конца, значит, все вершины покрашены
        return true;
    }

    for (int c = 1; c <= k; ++c) { // Пробуем по очереди все доступные цвета от 1 до k

        if (isSafe(v, graph, color, c)) { // Проверяем, безопасен ли выбранный цвет
            color[v] = c; // Временно присваиваем этот цвет вершине

            // Рекурсивно вызываем функцию для следующей вершины (v + 1)
            if (graphColoringUtil(graph, k, color, v + 1)) {
                return true; // Если дальше всё покрасилось успешно, возвращаем true
            }

            color[v] = 0; // если путь привел к тупику, сбрасываем цвет обратно в 0
        }
    }

    return false; // Если ни один цвет не подошел
}

bool graphColoring(const vector<vector<int>>& graph, int k) {// Основная фун-я, которая запускает алгоритм и выводит результат
    int n = graph.size(); // Узнаем количество вершин в графе
    vector<int> color(n, 0); // Создаем массив цветов и заполняем нулями 0 — не покрашена

    if (!graphColoringUtil(graph, k, color, 0)) {// Запускаем рекурсию с нулевой вершины. Если решение не найдено пишем
        cout << "Решение не найдено: нельзя раскрасить граф в " << k << " цветов.\n";
        return false;
    }


    cout << "Граф успешно раскрашен в " << k << " цветов. Цвета вершин:\n";// Если решение найдено, выводим его на экран
    for (int i = 0; i < n; ++i) {// цикл для последовательного перебора всех вершин графа ( от 0 до n-1)
        cout << "Вершина " << i << " -> Цвет " << color[i] << "\n";//выводим на экран номер текущей вершины и назначеный ей цвет
    }
    return true;//возвращаем true подтверждая что раскраска успешно выполнена и выведена
}

// Главная функция программы точка входа
int main() {
    setlocale(LC_ALL, "Russian"); // Настраиваем кириллицу для правильного отображения в консоли

    int n, k;
    cout << "Введите количество вершин в графе: ";
    cin >> n;

    cout << "Введите количество доступных цветов: ";
    cin >> k;


    vector<vector<int>> graph(n, vector<int>(n)); // Создаем матрицу смежности нужного размера под введенное количество вершин

    cout << "Введите матрицу смежности (строка за строкой, разделяя числа пробелами):\n";
    for (int i = 0; i < n; ++i) { // внешний цикл проходим по каждой строке матрицы по порядку вершин
        for (int j = 0; j < n; ++j) {// внутрений цикл проходим по каждому элементу в строке по столбцам
            cin >> graph[i][j];//считываем с клавы значение (0 или 1) для текущей ячейки матрицы
        }
    }


    graphColoring(graph, k); // Запускаем алгоритм с введенными вами данными

    cin.get();
    cin.get(); // Двойной вызов нужен, чтобы консоль не закрывалась сразу после ввода матрицы
    return 0;  // Завершение программы
}
